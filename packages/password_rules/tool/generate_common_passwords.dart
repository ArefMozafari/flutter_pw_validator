// Regenerates lib/src/common_passwords.dart from a newline-separated list.
//
// Usage, from packages/password_rules:
//   dart run tool/generate_common_passwords.dart <list.txt> <source-url> <blob-sha>
import 'dart:io';

const String _outputPath = 'lib/src/common_passwords.dart';

String _escape(String password) => password
    .replaceAll(r'\', r'\\')
    .replaceAll("'", r"\'")
    .replaceAll(r'$', r'\$');

void main(List<String> arguments) {
  final [inputPath, sourceUrl, blobSha] = arguments;
  final passwords = File(inputPath)
      .readAsLinesSync()
      .map((line) => line.trim().toLowerCase())
      .where((line) => line.isNotEmpty)
      .toSet();
  final buffer = StringBuffer()
    ..writeln(
      '// GENERATED by tool/generate_common_passwords.dart. Do not edit.',
    )
    ..writeln('//')
    ..writeln('// Source: $sourceUrl')
    ..writeln('// Blob: $blobSha')
    ..writeln('// License of the source list: MIT, Daniel Miessler (SecLists).')
    ..writeln()
    ..writeln(
      '/// The ${passwords.length} most common leaked passwords, lowercased.',
    )
    ..writeln('const Set<String> commonPasswords = {');
  for (final password in passwords) {
    buffer.writeln("  '${_escape(password)}',");
  }
  buffer.writeln('};');
  File(_outputPath).writeAsStringSync(buffer.toString());
  stdout.writeln('Wrote ${passwords.length} passwords to $_outputPath');
}
